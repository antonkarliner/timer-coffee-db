CREATE OR REPLACE FUNCTION public.add_subscriber(subscriber_email text)
 RETURNS TABLE(generated_token uuid, already_exists boolean)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
AS $function$
DECLARE
  existing_subscriber RECORD;
  new_token UUID;
BEGIN
  -- Check if email already exists
  SELECT id, email, confirmed, token INTO existing_subscriber
  FROM public.blog_subscribers
  WHERE email = subscriber_email;

  IF FOUND THEN
     -- Return existing token and indicate user already exists
     RETURN QUERY SELECT existing_subscriber.token, true;
  ELSE
      -- Insert new subscriber and return the generated token
      INSERT INTO public.blog_subscribers (email)
      VALUES (subscriber_email)
      RETURNING token INTO new_token;

      RETURN QUERY SELECT new_token, false;
  END IF;
END;
$function$
;

CREATE OR REPLACE FUNCTION public.can_access_user_recipe(user_id text, recipe_id text)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
  r RECORD;
BEGIN
  -- Look up the recipe in public.user_recipes
  SELECT * INTO r FROM public.user_recipes WHERE id = recipe_id;

  -- If no recipe found, return false
  IF NOT FOUND THEN
    RETURN false;
  END IF;

  -- Check if the recipe belongs to the current user
  IF SUBSTRING(r.vendor_id, 5) = user_id THEN
    RETURN true;
  END IF; -- Added END IF for clarity

  -- Check if the recipe is public (NEW CHECK)
  IF r.ispublic = true THEN
      RETURN true;
  END IF;

  -- Check if the recipe was imported from another recipe
  IF r.import_id IS NOT NULL THEN
    -- If the original recipe creator is the current user
    IF r.import_id LIKE 'usr-' || user_id || '-%' THEN
      RETURN true;
    -- Check if the original recipe is public
    ELSIF EXISTS (
      SELECT 1 FROM public.user_recipes
      WHERE id = r.import_id AND ispublic = true
    ) THEN
      RETURN true;
    END IF;
  END IF;

  RETURN false; -- Default to false if no other condition met
END;
$function$
;

