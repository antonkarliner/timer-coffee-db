CREATE OR REPLACE FUNCTION public.maintain_normalized_names()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
DECLARE
  alias_array   text[];
  normalized    text[];
  single_alias  text;
BEGIN
  --------------------------------------------------------------------------------
  -- 1) Normalize roaster_name
  --    If roaster_name is NULL, also set normalized_name to NULL
  --------------------------------------------------------------------------------
  IF NEW.roaster_name IS NOT NULL THEN
    NEW.normalized_name := lower(unaccent(NEW.roaster_name));
  ELSE
    NEW.normalized_name := NULL;
  END IF;

  --------------------------------------------------------------------------------
  -- 2) Normalize aliases (comma-separated)
  --    We'll split on commas, trim each piece, unaccent, lower, then rejoin
  --------------------------------------------------------------------------------
  IF NEW.aliases IS NOT NULL THEN
    alias_array := string_to_array(NEW.aliases, ',');  -- split on commas
    normalized := array[]::text[];
    
    FOREACH single_alias IN ARRAY alias_array
    LOOP
      single_alias := trim(single_alias);
      single_alias := lower(unaccent(single_alias));
      normalized := array_append(normalized, single_alias);
    END LOOP;
    
    NEW.normalized_aliases := array_to_string(normalized, ',');
  ELSE
    NEW.normalized_aliases := NULL;
  END IF;

  RETURN NEW;
END;
$function$
;

CREATE OR REPLACE FUNCTION public.search_roaster_candidates(in_value text, match_threshold double precision)
 RETURNS TABLE(roaster_name text, aliases text, sim_score double precision)
 LANGUAGE sql
AS $function$
WITH words_to_strip (word) AS (
  VALUES ('roastery'), ('roasters'), ('coffee'), ('cafe'), ('company'), ('co')
),
normalized_input_val AS (
  SELECT unaccent(lower(in_value)) AS val
),
stripped_input AS (
  SELECT
    (SELECT val FROM normalized_input_val) AS original_input,
    trim(regexp_replace((SELECT val FROM normalized_input_val), array_to_string(array(SELECT word FROM words_to_strip), '|', ''), 'gi')) AS stripped_input_val
),
db_roasters_normalized AS (
  SELECT
    r.roaster_name AS original_roaster_name,
    r.aliases AS original_aliases,
    r.normalized_name,
    unnest(string_to_array(r.normalized_aliases, ',')) AS single_alias
  FROM public.coffee_roasters r
),
db_roasters_stripped AS (
  SELECT
    drn.original_roaster_name,
    drn.original_aliases,
    drn.normalized_name AS original_normalized_name,
    trim(regexp_replace(drn.normalized_name, array_to_string(array(SELECT word FROM words_to_strip), '|', ''), 'gi')) AS stripped_normalized_name,
    drn.single_alias AS original_single_alias,
    trim(regexp_replace(drn.single_alias, array_to_string(array(SELECT word FROM words_to_strip), '|', ''), 'gi')) AS stripped_single_alias
  FROM db_roasters_normalized drn
),
all_comparisons AS (
  SELECT
    drs.original_roaster_name,
    drs.original_aliases,
    GREATEST(
      similarity(drs.original_normalized_name, (SELECT original_input FROM stripped_input)),
      similarity(drs.stripped_normalized_name, (SELECT stripped_input_val FROM stripped_input)),
      similarity(drs.original_normalized_name, (SELECT stripped_input_val FROM stripped_input)),
      similarity(drs.stripped_normalized_name, (SELECT original_input FROM stripped_input)),

      similarity(drs.original_single_alias, (SELECT original_input FROM stripped_input)),
      similarity(drs.stripped_single_alias, (SELECT stripped_input_val FROM stripped_input)),
      similarity(drs.original_single_alias, (SELECT stripped_input_val FROM stripped_input)),
      similarity(drs.stripped_single_alias, (SELECT original_input FROM stripped_input))
    ) AS calculated_sim_score
  FROM db_roasters_stripped drs
)
SELECT DISTINCT
  ac.original_roaster_name,
  ac.original_aliases,
  ac.calculated_sim_score AS sim_score
FROM all_comparisons ac
WHERE ac.calculated_sim_score > match_threshold
ORDER BY sim_score DESC
LIMIT 20;
$function$
;

CREATE OR REPLACE FUNCTION public.search_roaster_unaccent(search_name text)
 RETURNS SETOF coffee_roasters
 LANGUAGE sql
 STABLE
AS $function$
  SELECT *
  FROM coffee_roasters
  WHERE (
    unaccent(lower(roaster_name)) = unaccent(lower(search_name))
    OR unaccent(lower(aliases)) ILIKE '%' || unaccent(lower(search_name)) || '%'
  )
  LIMIT 1
$function$
;

CREATE OR REPLACE FUNCTION public.translate_launch_popup()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
DECLARE
    project_url TEXT := (SELECT decrypted_secret FROM supabase_vault.decrypted_secrets WHERE name = 'supabase_url');
    edge_function_url TEXT;
    locales TEXT[];
    response JSONB;
BEGIN
    IF project_url IS NULL THEN
        RAISE EXCEPTION 'Vault secret ''supabase_url'' is not set';
    END IF;
    edge_function_url := project_url || '/functions/v1/translate-openai';

    -- Check if the row is already translated to skip
    IF NEW.is_translated IS TRUE THEN
        RETURN NEW;
    END IF;

    -- Set the statement timeout for this function to allow longer processing time
    SET LOCAL statement_timeout = '300000'; -- 300 seconds or 5 minutes

    -- Set the HTTP request timeout options
    PERFORM extensions.http_set_curlopt('CURLOPT_TIMEOUT', '300'); -- 300 seconds or 5 minutes for CURLOPT_TIMEOUT
    PERFORM extensions.http_set_curlopt('CURLOPT_CONNECTTIMEOUT', '120'); -- 120 seconds or 2 minutes for CURLOPT_CONNECTTIMEOUT

    -- Fetch supported locales except 'en'
    SELECT array_agg(locale) INTO locales FROM supported_locales WHERE locale != 'en';

    -- Send the English content and supported locales to the Edge function
    response := (SELECT content::jsonb FROM http_post(
        edge_function_url,
        jsonb_build_object(
            'text', NEW.content,
            'locales', locales
        )::text,
        'application/json'
    ));

    -- Check the response to ensure it is not null or empty
    IF response IS NULL THEN
        RAISE EXCEPTION 'HTTP request timed out or failed';
    END IF;

    -- Update the row to set is_translated to true to prevent re-triggering
    NEW.is_translated := true;

    RETURN NEW;
END;
$function$
;


