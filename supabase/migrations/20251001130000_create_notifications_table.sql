-- Create notifications table
CREATE TABLE public.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content TEXT NOT NULL,
    locale VARCHAR(10) NOT NULL REFERENCES public.supported_locales(locale),
    platform TEXT DEFAULT 'all' CHECK (platform IN ('all', 'ios', 'android', 'web')),
    deep_link TEXT,
    is_translated BOOLEAN DEFAULT FALSE,
    is_sent BOOLEAN DEFAULT FALSE,
    scheduled_at TIMESTAMPTZ,
    sent_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Create indexes for performance
CREATE INDEX idx_notifications_scheduled_at ON public.notifications(scheduled_at) WHERE is_sent = FALSE;
CREATE INDEX idx_notifications_locale ON public.notifications(locale);
CREATE INDEX idx_notifications_platform ON public.notifications(platform);
CREATE INDEX idx_notifications_is_translated ON public.notifications(is_translated);
CREATE INDEX idx_notifications_is_sent ON public.notifications(is_sent);

-- Create RLS policy
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;

-- Policy for service role (full access)
CREATE POLICY "Service role full access" ON public.notifications
    FOR ALL USING (auth.jwt()->>'role' = 'service_role');

-- Policy for authenticated users (read only)
CREATE POLICY "Authenticated read access" ON public.notifications
    FOR SELECT USING (auth.role() = 'authenticated');

-- Create function to automatically update updated_at column
CREATE OR REPLACE FUNCTION public.update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Create updated_at trigger
CREATE TRIGGER update_notifications_updated_at
    BEFORE UPDATE ON public.notifications
    FOR EACH ROW
    EXECUTE FUNCTION public.update_updated_at_column();